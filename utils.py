import re
import streamlit as st
from fpdf import FPDF


def init_session_state():
    """Initializes Streamlit session state variables."""
    if "chat_history" not in st.session_state:
        st.session_state.chat_history = []
    if "analysis_result" not in st.session_state:
        st.session_state.analysis_result = None
    if "parsed_ingredients" not in st.session_state:
        st.session_state.parsed_ingredients = []
    if "allergen_results" not in st.session_state:
        st.session_state.allergen_results = []


def sanitize_ascii(text) -> str:
    """Converts any input safely to pure ASCII string to prevent FPDF unicode errors."""
    if not text:
        return ""
    return str(text).encode('ascii', 'ignore').decode('ascii').strip()


def create_download_report(product_name, user_allergies, dietary_prefs,
                           analysis_summary, filepath="allergen_report.pdf"):
    """
    Generate a complete, non-blank PDF report.
    Compatible with fpdf2 >= 2.7 (uses new_x / new_y instead of ln).
    """
    pdf = FPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # ============================================================
    # TITLE
    # ============================================================
    pdf.set_font("Helvetica", 'B', 16)
    pdf.set_text_color(30, 80, 180)
    pdf.cell(0, 10, "IngredientCheck AI - Safety Analysis Report",
             new_x="LMARGIN", new_y="NEXT", align='C')
    pdf.set_text_color(0, 0, 0)
    pdf.ln(5)

    # ============================================================
    # PRODUCT DETAILS
    # ============================================================
    pdf.set_font("Helvetica", 'B', 11)
    pdf.cell(0, 7, f"Product Name: {sanitize_ascii(product_name)}",
             new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", '', 10)
    allergies_str = ", ".join(user_allergies) if user_allergies else "None"
    diet_str = ", ".join(dietary_prefs) if dietary_prefs else "None"

    pdf.cell(0, 6, f"User Active Allergies: {sanitize_ascii(allergies_str)}",
             new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, f"Dietary Preferences: {sanitize_ascii(diet_str)}",
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)

    # ============================================================
    # SAFETY SUMMARY HEADER
    # ============================================================
    pdf.set_font("Helvetica", 'B', 12)
    pdf.cell(0, 8, "Safety Summary",
             new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", '', 10)

    # Convert summary safely to string
    if isinstance(analysis_summary, dict):
        summary_text = "\n".join([f"{k}: {v}" for k, v in analysis_summary.items()])
    else:
        summary_text = str(analysis_summary)

    # Clean markdown noise
    cleaned_summary = summary_text.replace("**", "").replace("###", "").strip()

    # Guarantee at least SOME body text (prevents completely blank PDF)
    cleaned_summary = sanitize_ascii(cleaned_summary)
    if not cleaned_summary:
        cleaned_summary = "(No textual summary available.)"

    pdf.multi_cell(0, 6, cleaned_summary,
                   new_x="LMARGIN", new_y="NEXT")

    # ============================================================
    # FOOTER
    # ============================================================
    pdf.ln(6)
    pdf.set_font("Helvetica", 'I', 9)
    pdf.set_text_color(100, 100, 100)
    pdf.multi_cell(
        0, 5,
        "This report is generated by IngredientCheck AI "
        "and is not a medical diagnosis.",
        new_x="LMARGIN", new_y="NEXT"
    )

    # ============================================================
    # SAVE
    # ============================================================
    pdf.output(filepath)
    return filepath